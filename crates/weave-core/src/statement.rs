//! The statement merge: an entity body is a container in miniature.
//!
//! `container.rs` gave a class body the discipline `region.rs` gives a file —
//! DECOMPOSE into segments that tile the input, merge the segments by identity,
//! fold the results back. This module is the same move one level further down,
//! and it is the last one: when both sides edit the same *function* body and
//! diff3 refuses it, the body is partitioned into STATEMENTS, the statement
//! triples are classified with the same actions the entity triples use,
//! and the merge is a fold over the partition.
//!
//! Three properties are load-bearing, and each is structural rather than
//! argued:
//!
//!   1. **Partition identity.** `header + prelude + Σ(lead + text) + tail +
//!      footer` reproduces the input byte for byte. The pieces tile the body,
//!      so "a stage rebuilt text out of the pieces it understood, and whatever
//!      it did not understand ceased to exist" is not a sentence this module
//!      can be the subject of.
//!
//!   2. **Linear claims.** A `Part` is moved into exactly one triple by a
//!      claim token — `BasePart` / `OursPart` / `TheirsPart`, three distinct
//!      types generated by the `part_claim!` macro, none of them `Copy` or
//!      `Clone`, all of them minted only by the partitioner. A statement byte is therefore owned once: emitting one
//!      statement twice is a program that does not compile, exactly as
//!      `v2::types::Claim` makes it for entities.
//!
//!   3. **Refinement, never trade.** This merge is reached only from a position
//!      that is *already* a conflict — after `diffy`, after `git merge-file`,
//!      after the decorator merge, after the container merge. Every verdict it
//!      can change is therefore CONFLICT → something; no clean merge in the
//!      universe routes through here, so no clean merge can be turned into a
//!      different clean merge by it. So this pass can only turn a conflict into
//!      something else, never a clean merge into a different one — and the tests
//!      check that directly anyway, because an argument nobody runs is a comment.
//!
//! The container is ORDER-EFFECTFUL. Members of a class are unordered children;
//! statements of a body are a sequence, and executing them in the other order
//! is a different program. So placement here is not `container::member_order`'s
//! "shared base coordinate" — it is the order-preserving union of what the two
//! sides asserted, with an honest conflict wherever the two assertions
//! interleave ambiguously (two independent insertions into the SAME gap have no
//! separator between them, so choosing an order for them is choosing a program
//! neither side wrote).
//!
//! Recursion stops at a COUNTER, not at an argument. A statement that is itself
//! a block — an `if`, a `for`, a `switch` — is partitioned again by the same
//! fold when diff3 refuses it, down to [`MAX_DEPTH`]. The bound is not decoration:
//! a body whose partition is a single block statement recurses on text that is
//! very nearly itself, so "the input shrinks" is not available as a termination
//! measure and the depth counter is the well-founded one.
//!
//! Below the bottom level, and below a statement that is not a block, there is
//! one more partition and then there is diff3. Two disjoint edits to a single
//! LINE used to stay a conflict here, because composing them needs a partition
//! into TOKENS and that partition's failure mode is new — a syntactically valid
//! sentence neither side wrote. [`crate::expression`] is
//! that partition, and it is reached from exactly one arm of this module: the
//! `(Edited, Edited)` cell, after `formatting_tie`, after diff3, after the block
//! recursion, immediately before the marker. It answers `None` for everything it
//! is not sure of, so the arm it sits in still writes the same marker it always
//! did unless a composition is licensed outright.
//!
//! That one addition is what makes [`fabricates_lines`] take an allowlist. A
//! token composition is a line no version wrote — that is what composing means —
//! so the backstop is told exactly which lines were composed and admits those
//! and nothing else.

