/// May two blocks of statements inserted into the same gap both land, and if
/// so, what did each of them bind?
///
/// The default answer is no. Two independent insertions into one gap have no
/// separator between them, so every order is a program and none of them is one
/// a side wrote. Two shapes escape that, and they are
/// different arguments:
///
/// **Independent declarations**, always available. Every statement in both
/// blocks binds exactly one name and does nothing else observable; the blocks
/// bind disjoint names; and neither mentions a name the other binds. For
/// example: two sides each appending their own feature flags to a class
/// attribute block.
///
/// **Disjoint-write composition**, only under [`License::Footprint`]. The declaration gate
/// is a *sufficient* condition stated as a syntactic shape, and it refuses
/// several things it has no reason to: a helper `def` each side added, a
/// declaration whose body spans lines, a block mixing the two. What actually
/// makes an order unobservable is that neither block writes what the other
/// writes and neither writes what the other reads.
/// [`crate::binding::footprint`] answers `None` for anything whose effect it
/// cannot see, so a bare call, a `return`, an `if`, a `+=` or a decorated
/// definition still refuses the gap.
///
/// Two sides appending *calls* to a function body is refused under both, and
/// that is not an oversight: `flush()` and `retry()` read and write
/// whatever they touch, and this reader has no name for those effects.
fn same_gap_composition_licensed(
    mine: &[Part],
    yours: &[Part],
    license: License,
) -> Option<LicensedGap> {
    if mine.is_empty() || yours.is_empty() {
        return None;
    }
    if let Some(g) = independent_declarations(mine, yours) {
        return Some(g);
    }
    if license != License::Footprint {
        return None;
    }
    let cat = |ps: &[Part]| -> String {
        let mut s = String::new();
        for p in ps {
            s.push_str(&p.text);
            if !s.ends_with('\n') {
                s.push('\n');
            }
        }
        s
    };
    let (fm, fy) = (footprint(&cat(mine))?, footprint(&cat(yours))?);
    if !footprints_disjoint(&fm, &fy) {
        return None;
    }
    Some(LicensedGap {
        ours_binds: fm.defines.into_iter().collect(),
        theirs_binds: fy.defines.into_iter().collect(),
    })
}

/// The declaration gate, unchanged in meaning: every statement in both blocks
/// binds exactly one name and nothing else, the two blocks bind disjoint names,
/// and neither block mentions a name the other binds.
fn independent_declarations(mine: &[Part], yours: &[Part]) -> Option<LicensedGap> {
    use std::collections::HashSet;
    let names = |ps: &[Part]| -> Option<Vec<String>> {
        ps.iter().map(|p| declared_name(&p.text)).collect()
    };
    let (mn, yn) = (names(mine)?, names(yours)?);
    let mset: HashSet<&String> = mn.iter().collect();
    let yset: HashSet<&String> = yn.iter().collect();
    if mset.intersection(&yset).next().is_some() {
        return None;
    }
    let mentions = |ps: &[Part], who: &HashSet<&String>| -> bool {
        ps.iter().any(|p| {
            word_tokens(&p.text)
                .iter()
                .any(|w| who.contains(&w.to_string()))
        })
    };
    if mentions(mine, &yset) || mentions(yours, &mset) {
        return None;
    }
    Some(LicensedGap {
        ours_binds: mn,
        theirs_binds: yn,
    })
}

/// Two renderings of the same statement that differ only in the spaces BETWEEN
/// their tokens — same line count, same indentation on every line, same tokens
/// in the same order. Returns the winner, chosen by the bytes so that the
/// answer does not depend on which side is ours.
///
/// Leading whitespace is excluded from "formatting" on purpose: in an
/// indentation-scoped language a dedent can move a statement between blocks,
/// so calling that formatting would silently discard a structural edit.
fn formatting_tie(a: &str, b: &str) -> Option<String> {
    let (la, lb): (Vec<&str>, Vec<&str>) = (a.lines().collect(), b.lines().collect());
    if la.len() != lb.len() {
        return None;
    }
    for (x, y) in la.iter().zip(lb.iter()) {
        let indent = |s: &str| s.len() - s.trim_start().len();
        if indent(x) != indent(y) {
            return None;
        }
        if x.split_whitespace().ne(y.split_whitespace()) {
            return None;
        }
    }
    Some(if a <= b { a.to_string() } else { b.to_string() })
}

/// A side-independent sort key for a block of inserted statements.
fn key_of(parts: &[Part]) -> String {
    let mut out = String::new();
    for p in parts {
        out.push_str(&p.key);
    }
    out
}

/// A short human label for a statement, for conflict markers: the first line,
/// trimmed and clipped. A marker that names nothing sends the reader to the
/// whole file.
fn label(text: &str) -> String {
    let first = text.lines().find(|l| !l.trim().is_empty()).unwrap_or("");
    let t = first.trim();
    if t.chars().count() > 48 {
        let clipped: String = t.chars().take(45).collect();
        format!("{clipped}...")
    } else {
        t.to_string()
    }
}

/// Merge an entity body statement-wise, or `None` if this reader does not
/// understand the body well enough to be trusted with it.
///
/// `None` costs the caller the whole-entity conflict it would have raised
/// anyway, which is why every uncertainty in here answers `None` rather than
/// guessing.
pub(crate) fn statement_merge(
    base: &str,
    ours: &str,
    theirs: &str,
    fmt: &ScopeMarkers<'_>,
) -> Option<InnerMergeResult> {
    statement_merge_inner(
        base,
        ours,
        theirs,
        fmt,
        0,
        License::Refused,
        &mut Vec::new(),
        &mut Vec::new(),
    )
}

/// How much authority the fold has over two blocks inserted into the same gap.
///
/// The default is [`License::Refused`]: two independent insertions into one gap
/// have no separator between them, so every order is a program and none of them
/// is one a side wrote. The one exception the fold has
/// always made is `independent_declarations` — a shape where the two orders are
/// the same program.
///
/// [`License::Footprint`] widens that exception to any two blocks with disjoint
/// read/write sets, and it is granted by `v2::bind` and by nobody else, only on
/// a triple that is **already a conflict**. That is what keeps the pass one-way: a mode
/// that can only be entered from a conflict can only leave one.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum License {
    Refused,
    Footprint,
}

/// Evidence for one licensed composition: what each side's block binds.
#[derive(Debug, Clone)]
pub(crate) struct LicensedGap {
    pub ours_binds: Vec<String>,
    pub theirs_binds: Vec<String>,
}

/// The fold at an explicit license. `container.rs` needs this because a member
/// body is reached through the container merge rather than directly, so the
/// license has to travel with the call rather than with the entry point.
pub(crate) fn statement_merge_with(
    base: &str,
    ours: &str,
    theirs: &str,
    fmt: &ScopeMarkers<'_>,
    license: License,
    evidence: &mut Vec<LicensedGap>,
) -> Option<InnerMergeResult> {
    statement_merge_inner(
        base,
        ours,
        theirs,
        fmt,
        0,
        license,
        evidence,
        &mut Vec::new(),
    )
}

/// The fold, with disjoint-write composition available to the same-gap arm. Returns the
/// evidence for every composition the license paid for, so the caller can put
/// it on the findings channel — a resolution nobody can see the reason for is
/// not a resolution, it is a guess with better manners.
pub(crate) fn statement_merge_licensed(
    base: &str,
    ours: &str,
    theirs: &str,
    fmt: &ScopeMarkers<'_>,
) -> Option<(InnerMergeResult, Vec<LicensedGap>)> {
    let mut evidence = Vec::new();
    let r = statement_merge_inner(
        base,
        ours,
        theirs,
        fmt,
        0,
        License::Footprint,
        &mut evidence,
        &mut Vec::new(),
    )?;
    Some((r, evidence))
}

/// How far the fold may recurse. Depth 0 is the entity body, depth 1 the block
/// inside one of its statements, and so on down.
///
/// The bound is what makes termination a fact rather than an argument. The
/// recursion is NOT justified by "the input shrinks" — a body whose partition is
/// a single block statement recurses on text that may be very nearly itself —
/// so the depth counter is the well-founded measure, and it is the only one.
/// Three levels is where the evidence runs out in practice: past a nested `for`
/// inside an `if` inside a method, the partition is guessing about a grammar
/// nobody parsed.
const MAX_DEPTH: u8 = 3;

fn statement_merge_inner(
    base: &str,
    ours: &str,
    theirs: &str,
    fmt: &ScopeMarkers<'_>,
    depth: u8,
    license: License,
    evidence: &mut Vec<LicensedGap>,
    // Lines the expression fold composed, at this level and below. The
    // no-fabrication backstop licenses exactly these — see `fabricates_lines`.
    composed: &mut Vec<String>,
) -> Option<InnerMergeResult> {
    let b = partition(base)?;
    let o = partition(ours)?;
    let t = partition(theirs)?;

    // One statement per side is not a partition worth having AT THE BOTTOM: the
    // fold degenerates to the diff3 that already refused this body. It is worth
    // having above the bottom, because that one statement is a block, and the
    // level below it is where the two sides' edits become separable — a method
    // whose whole body is a single `if` is otherwise never looked inside.
    if b.parts.len() < 2 && o.parts.len() < 2 && t.parts.len() < 2 && depth >= MAX_DEPTH {
        return None;
    }

    let ours_align = align(&b, &o)?;
    let theirs_align = align(&b, &t)?;

    // Mint the claims. From here on a statement is reached only through the
    // claim that names it, and a claim is spent once.
    let base_claims: Vec<BasePart> = b.claims(BasePart::new);
    let ours_claims: Vec<OursPart> = o.claims(OursPart::new);
    let theirs_claims: Vec<TheirsPart> = t.claims(TheirsPart::new);

    let mut has_conflict = false;
    let mut out = String::new();
    out.push_str(&merge_trivia(
        "declaration",
        &b.header,
        &o.header,
        &t.header,
        fmt,
        &mut has_conflict,
    ));
    out.push_str(&merge_trivia(
        "body prelude",
        &b.prelude,
        &o.prelude,
        &t.prelude,
        fmt,
        &mut has_conflict,
    ));

    // Additions grouped by the gap they sit in.
    let mut ours_adds: HashMap<usize, Vec<usize>> = HashMap::new();
    for (gap, s) in &ours_align.additions {
        ours_adds.entry(*gap).or_default().push(*s);
    }
    let mut theirs_adds: HashMap<usize, Vec<usize>> = HashMap::new();
    for (gap, s) in &theirs_align.additions {
        theirs_adds.entry(*gap).or_default().push(*s);
    }

    let render = |part: &Part| -> String {
        let mut s = part.lead.clone();
        s.push_str(&part.text);
        s
    };

    // Two independent insertions into the same gap have no separator between
    // them: every order is a program, and none of them is
    // one a side wrote. Identical insertions are not two insertions — and
    // neither are two blocks of DECLARATIONS that cannot see each other, which
    // is the one shape where "what order" is a question with no answer to get
    // wrong (see `independent_declarations`).
    let emit_gap =
        |gap: usize, out: &mut String, has_conflict: &mut bool, licensed: &mut Vec<LicensedGap>| {
            let pick = |adds: &HashMap<usize, Vec<usize>>,
                        parts: &[Part],
                        idx: &dyn Fn(usize) -> usize|
             -> Vec<Part> {
                adds.get(&gap)
                    .map(|v| v.iter().map(|&s| parts[idx(s)].clone()).collect())
                    .unwrap_or_default()
            };
            let mine_parts = pick(&ours_adds, &o.parts, &|s| ours_claims[s].index());
            let yours_parts = pick(&theirs_adds, &t.parts, &|s| theirs_claims[s].index());
            let cat = |ps: &[Part]| -> String { ps.iter().map(render).collect() };
            let (mine, yours) = (cat(&mine_parts), cat(&yours_parts));
            match (mine.is_empty(), yours.is_empty()) {
                (true, true) => {}
                (false, true) => out.push_str(&mine),
                (true, false) => out.push_str(&yours),
                (false, false) => {
                    if mine == yours {
                        out.push_str(&mine);
                    } else if let Some(binds) =
                        same_gap_composition_licensed(&mine_parts, &yours_parts, license)
                    {
                        licensed.push(binds);
                        // Both blocks land, in the order their own bytes decide —
                        // never in the order the caller happened to name the sides,
                        // so the merge is the same from either direction.
                        let (first, second) = if key_of(&mine_parts) <= key_of(&yours_parts) {
                            (&mine, &yours)
                        } else {
                            (&yours, &mine)
                        };
                        out.push_str(first);
                        out.push_str(second);
                    } else {
                        *has_conflict = true;
                        out.push_str(&scoped_conflict_marker(
                            "inserted statements",
                            None,
                            Some(&mine),
                            Some(&yours),
                            false,
                            false,
                            fmt,
                        ));
                    }
                }
            }
        };

    for (i, claim) in base_claims.iter().enumerate() {
        emit_gap(i, &mut out, &mut has_conflict, evidence);
        let bp = &b.parts[claim.index()];
        // Action and statement resolved together, once: from here on "this side
        // edited" and "here is what it edited it to" are the same fact.
        // `align(&b, ..)` returns one action per base statement, and `i` walks
        // `base_claims`, which is one claim per base statement — so `per_base[i]`
        // is in range. The claim indices are this side's own, see `resolve`.
        let ao = SideEdit::resolve(&ours_align.per_base[i], &o.parts, |s| {
            // This side's own claim vector, indexed by this side's own action.
            ours_claims[s].index()
        });
        let at = SideEdit::resolve(&theirs_align.per_base[i], &t.parts, |s| {
            // Same argument, theirs' side of it.
            theirs_claims[s].index()
        });
        let (op, tp) = (ao.part(), at.part());
        let name = label(&bp.text);

        // The lead is decided by the versions that still HAVE the statement. A
        // version that deleted it did not empty the gap in front of it.
        let lead = match (&ao, &at) {
            (SideEdit::Deleted, SideEdit::Deleted) => None,
            (SideEdit::Deleted, _) => Some(tp.map(|p| p.lead.clone()).unwrap_or(bp.lead.clone())),
            (_, SideEdit::Deleted) => Some(op.map(|p| p.lead.clone()).unwrap_or(bp.lead.clone())),
            _ => {
                let lo = op.map(|p| p.lead.as_str()).unwrap_or(&bp.lead);
                let lt = tp.map(|p| p.lead.as_str()).unwrap_or(&bp.lead);
                Some(merge_trivia(
                    &format!("before {name}"),
                    &bp.lead,
                    lo,
                    lt,
                    fmt,
                    &mut has_conflict,
                ))
            }
        };

        // One arm per (ours, theirs) action pair over
        // {UNCHANGED, EDITED, DELETED}.
        let body: Option<String> = match (&ao, &at) {
            (SideEdit::Unchanged, SideEdit::Unchanged) => Some(bp.text.clone()),
            (SideEdit::Unchanged, SideEdit::Edited(pt)) => Some(pt.text.clone()),
            (SideEdit::Edited(po), SideEdit::Unchanged) => Some(po.text.clone()),
            (SideEdit::Edited(eo), SideEdit::Edited(et)) => {
                let (po, pt) = (&eo.text, &et.text);
                if po == pt {
                    Some(po.clone())
                } else if let Some(text) = formatting_tie(po, pt) {
                    // Same statement, same columns, same tokens, different
                    // spaces between them. There is no program here to get
                    // wrong, so there is nothing for a human to decide — and the
                    // winner is chosen by the bytes rather than by which side
                    // the caller happened to name first.
                    Some(text)
                } else {
                    // Depth 1 is enough: what is inside one statement is text,
                    // and text is diff3's leaf.
                    // `git merge-file` is deliberately NOT the second opinion
                    // here, though it is one level up. Spawning it costs a
                    // subprocess per call, and a body has tens of statements
                    // with this fold recursing into each one, so the same
                    // tail-case tiebreaker turns into a per-statement
                    // subprocess. Measurement showed that cost without a
                    // matching gain in resolutions, since diff3 is already
                    // inside the process at this point.
                    diffy_merge(&bp.text, po, pt)
                        // The statement is itself a block — an `if`, a `for`, a
                        // `try` — and the same fold reads it. Bounded, and only
                        // when it comes back CLEAN: a nested conflict is the
                        // conflict this arm was already going to raise.
                        .or_else(|| {
                            if depth >= MAX_DEPTH {
                                return None;
                            }
                            statement_merge_inner(
                                &bp.text,
                                po,
                                pt,
                                fmt,
                                depth + 1,
                                license,
                                evidence,
                                composed,
                            )
                            .filter(|r| !r.has_conflicts)
                            .map(|r| r.content)
                        })
                        // The last zoom. Both sides edited this one statement,
                        // diff3 refused it, and it is not a block the fold can
                        // separate — so the statement is tiled into TOKENS and
                        // the two token edits are composed if, and only if, a
                        // base token neither side touched separates them.
                        // Reached from here and nowhere else, so the verdict
                        // it can change is CONFLICT → clean and nothing else.
                        .or_else(|| {
                            let c = crate::expression::expression_merge(&bp.text, po, pt)?;
                            composed.extend(c.composed_lines);
                            Some(c.text)
                        })
                        .or_else(|| {
                            has_conflict = true;
                            Some(scoped_conflict_marker(
                                &name,
                                Some(&bp.text),
                                Some(po),
                                Some(pt),
                                false,
                                false,
                                fmt,
                            ))
                        })
                }
            }
            (SideEdit::Unchanged, SideEdit::Deleted) | (SideEdit::Deleted, SideEdit::Unchanged) => {
                None
            }
            (SideEdit::Deleted, SideEdit::Deleted) => None,
            (SideEdit::Edited(po), SideEdit::Deleted) => {
                has_conflict = true;
                Some(scoped_conflict_marker(
                    &name,
                    Some(&bp.text),
                    Some(&po.text),
                    None,
                    false,
                    true,
                    fmt,
                ))
            }
            (SideEdit::Deleted, SideEdit::Edited(pt)) => {
                has_conflict = true;
                Some(scoped_conflict_marker(
                    &name,
                    Some(&bp.text),
                    None,
                    Some(&pt.text),
                    true,
                    false,
                    fmt,
                ))
            }
        };

        if let Some(text) = body {
            if let Some(lead) = lead {
                out.push_str(&lead);
            }
            out.push_str(&text);
            if !text.ends_with('\n') {
                out.push('\n');
            }
        }
    }
    emit_gap(base_claims.len(), &mut out, &mut has_conflict, evidence);

    out.push_str(&merge_trivia(
        "trailing statements",
        &b.tail,
        &o.tail,
        &t.tail,
        fmt,
        &mut has_conflict,
    ));
    out.push_str(&merge_trivia(
        "closing",
        &b.footer,
        &o.footer,
        &t.footer,
        fmt,
        &mut has_conflict,
    ));
    if !ours.ends_with('\n') {
        while out.ends_with('\n') {
            out.pop();
        }
    }

    // Two backstops on the finished bytes, because a partition is only as
    // honest as the reader that produced it.
    //
    // (1) Nothing all three versions agreed on may be missing — `container.rs`'s
    //     predicate, unchanged, and the one weave is measured on.
    // (2) Nothing may be present that no version wrote. A fold cannot fabricate
    //     a line, so a fabricated line means the fold is not what ran.
    if drops_unanimous_lines(base, ours, theirs, &out)
        || fabricates_lines(base, ours, theirs, &out, composed)
    {
        return None;
    }

    Some(InnerMergeResult {
        content: out,
        has_conflicts: has_conflict,
    })
}

/// Does `out` contain a non-blank line no version wrote and nothing licensed?
///
/// Conflict markers are the one thing this merge is allowed to invent, so they
/// and their contents are exempt — everything outside them must be somebody's
/// own bytes.
///
/// `licensed` is the exception the expression fold pays for. A token
/// composition is, by definition, a line that no version wrote — that is what
/// composing means — so a backstop that only knows the three inputs would veto
/// every one of them, and a backstop widened to "anything the fold felt like"
/// would stop being a backstop. The middle is this: `expression::expression_merge`
/// reports the exact lines it created, they are the only new lines admitted,
/// and every other new line still fails. A line that appears in the output
/// which the fold cannot account for is still evidence that the fold is not
/// what ran.
fn fabricates_lines(base: &str, ours: &str, theirs: &str, out: &str, licensed: &[String]) -> bool {
    use std::collections::HashSet;
    let mut known: HashSet<&str> = HashSet::new();
    for src in [base, ours, theirs] {
        for l in src.lines() {
            known.insert(l.trim_end());
        }
    }
    for l in licensed {
        known.insert(l.as_str());
    }
    out.lines().any(|l| {
        let t = l.trim_end();
        if t.trim().is_empty() {
            return false;
        }
        let s = t.trim_start();
        if s.starts_with('<') || s.starts_with('=') || s.starts_with('>') || s.starts_with('|') {
            // A marker line, or a line that begins with one of the characters a
            // marker begins with — either way not evidence of fabrication.
            return false;
        }
        if crate::conflict::refusal_body(s).is_some() {
            // The marker's own refusal line. It is part of the conflict's
            // rendering, not of the program.
            return false;
        }
        !known.contains(t)
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::conflict::MarkerFormat;

    const SAMPLES: &[&str] = &[
        // python
        "def f(x):\n    total = 0\n    for i in x:\n        total += i\n\n    # done\n    return total\n",
        // typescript
        "function f(x: number[]): number {\n  let total = 0;\n  for (const i of x) {\n    total += i;\n  }\n\n  // done\n  return total;\n}\n",
        // rust
        "fn f(x: &[i32]) -> i32 {\n    let mut total = 0;\n    for i in x {\n        total += i;\n    }\n\n    total\n}\n",
        // java
        "public int f(int[] x) {\n    int total = 0;\n    for (int i : x) {\n        total += i;\n    }\n    if (total > 0) {\n        total--;\n    } else {\n        total++;\n    }\n    return total;\n}\n",
        // go
        "func f(x []int) int {\n\ttotal := 0\n\tfor _, i := range x {\n\t\ttotal += i\n\t}\n\treturn total\n}\n",
        // continuation lines that indentation alone would split
        "fn g() {\n    foo(a,\nb);\n    bar();\n}\n",
        // rust lifetimes: an apostrophe that opens no string
        "fn h<'a>(s: &'a str) -> &'a str {\n    let t = s.trim();\n    t\n}\n",
    ];

    /// The property everything else rests on.
    #[test]
    fn a_partition_tiles_the_body_it_came_from() {
        for content in SAMPLES {
            let p = partition(content).unwrap_or_else(|| panic!("partitions: {content:?}"));
            let mut rebuilt = p.header.clone();
            rebuilt.push_str(&p.prelude);
            for part in &p.parts {
                rebuilt.push_str(&part.lead);
                rebuilt.push_str(&part.text);
            }
            rebuilt.push_str(&p.tail);
            rebuilt.push_str(&p.footer);
            assert_eq!(rebuilt, *content, "partition lost or duplicated text");
        }
    }

    #[test]
    fn a_continuation_line_does_not_start_a_statement() {
        let p = partition("fn g() {\n    foo(a,\nb);\n    bar();\n}\n").unwrap();
        assert_eq!(p.parts.len(), 2, "{:?}", p.parts);
        assert_eq!(p.parts[0].text, "    foo(a,\nb);\n");
    }

    #[test]
    fn an_else_arm_stays_with_its_if() {
        let p = partition(SAMPLES[3]).unwrap();
        let keys: Vec<&str> = p.parts.iter().map(|x| x.key.as_str()).collect();
        assert_eq!(keys.len(), 4, "{keys:?}");
        assert!(keys[2].starts_with("if (total > 0) {"), "{keys:?}");
        assert!(keys[2].contains("} else {"), "{keys:?}");
    }

    #[test]
    fn disjoint_statement_edits_merge() {
        let base = "fn f() {\n    let a = 1;\n    let b = 2;\n    let c = 3;\n}\n";
        let ours = "fn f() {\n    let a = 11;\n    let b = 2;\n    let c = 3;\n}\n";
        let theirs = "fn f() {\n    let a = 1;\n    let b = 2;\n    let c = 33;\n}\n";
        let r = statement_merge(
            base,
            ours,
            theirs,
            &ScopeMarkers::bare(&MarkerFormat::default()),
        )
        .expect("merges");
        assert!(!r.has_conflicts);
        assert_eq!(
            r.content,
            "fn f() {\n    let a = 11;\n    let b = 2;\n    let c = 33;\n}\n"
        );
    }

    #[test]
    fn a_move_is_not_a_conflict_with_an_edit_elsewhere() {
        let base = "fn f() {\n    a();\n    b();\n    c();\n}\n";
        // ours moves a() to the end; theirs edits b()
        let ours = "fn f() {\n    b();\n    c();\n    a();\n}\n";
        let theirs = "fn f() {\n    a();\n    b(1);\n    c();\n}\n";
        let r = statement_merge(
            base,
            ours,
            theirs,
            &ScopeMarkers::bare(&MarkerFormat::default()),
        )
        .expect("merges");
        assert!(!r.has_conflicts, "{}", r.content);
        assert_eq!(r.content, "fn f() {\n    b(1);\n    c();\n    a();\n}\n");
    }

    #[test]
    fn two_insertions_into_one_gap_are_a_conflict() {
        let base = "fn f() {\n    a();\n    z();\n}\n";
        let ours = "fn f() {\n    a();\n    m();\n    z();\n}\n";
        let theirs = "fn f() {\n    a();\n    n();\n    z();\n}\n";
        let r = statement_merge(
            base,
            ours,
            theirs,
            &ScopeMarkers::bare(&MarkerFormat::default()),
        )
        .expect("merges");
        assert!(r.has_conflicts, "{}", r.content);
    }

    #[test]
    fn insertions_into_different_gaps_both_land() {
        let base = "fn f() {\n    a();\n    z();\n    q();\n}\n";
        let ours = "fn f() {\n    a();\n    m();\n    z();\n    q();\n}\n";
        let theirs = "fn f() {\n    a();\n    z();\n    n();\n    q();\n}\n";
        let r = statement_merge(
            base,
            ours,
            theirs,
            &ScopeMarkers::bare(&MarkerFormat::default()),
        )
        .expect("merges");
        assert!(!r.has_conflicts, "{}", r.content);
        assert_eq!(
            r.content,
            "fn f() {\n    a();\n    m();\n    z();\n    n();\n    q();\n}\n"
        );
    }

    #[test]
    fn delete_versus_edit_of_one_statement_conflicts_on_that_statement() {
        let base = "fn f() {\n    a();\n    b();\n    c();\n}\n";
        let ours = "fn f() {\n    a();\n    c();\n}\n";
        let theirs = "fn f() {\n    a();\n    b(2);\n    c();\n}\n";
        let r = statement_merge(
            base,
            ours,
            theirs,
            &ScopeMarkers::bare(&MarkerFormat::default()),
        )
        .expect("merges");
        assert!(r.has_conflicts);
        assert!(r.content.contains("a();"), "{}", r.content);
        assert!(r.content.contains("c();"), "{}", r.content);
    }

    /// An unterminated literal is unrecoverable; an unbalanced bracket count is
    /// not. The first means everything after it was read as code that is not
    /// code; the second means the text is a fragment of something larger, which
    /// is what the recursive arm hands itself on every call.
    #[test]
    fn an_unterminated_literal_is_refused_but_a_fragment_is_not() {
        assert!(depths(&["fn f() {", "    /* open"]).is_none());
        assert!(
            depths(&["    a();", "}"]).is_some(),
            "a fragment still scans"
        );
        let d = depths(&["fn f() {", "    a();"]).expect("a fragment still scans");
        assert_eq!(d, vec![0, 1], "depth is reported, not judged");
    }

    /// The nesting level a fragment's statements sit at is the fragment's own,
    /// not zero — otherwise a block sliced out of a method has no statements at
    /// all and the fold never looks inside it.
    #[test]
    fn statements_are_found_at_the_fragments_own_level() {
        let p = partition("    if x:\n        a()\n        b()\n").expect("partitions");
        let keys: Vec<&str> = p.parts.iter().map(|x| x.key.as_str()).collect();
        assert_eq!(keys, vec!["a()\n", "b()\n"], "{keys:?}");
    }

    /// The same triple gives the same bytes, every time.
    #[test]
    fn the_statement_merge_is_a_function_of_its_inputs() {
        let base = "fn f() {\n    a();\n    b();\n    c();\n    d();\n}\n";
        let ours = "fn f() {\n    a2();\n    b();\n    c();\n    x();\n    d();\n}\n";
        let theirs = "fn f() {\n    a();\n    b();\n    c2();\n    d();\n}\n";
        let first = statement_merge(
            base,
            ours,
            theirs,
            &ScopeMarkers::bare(&MarkerFormat::default()),
        )
        .map(|r| (r.content, r.has_conflicts));
        for _ in 0..24 {
            let again = statement_merge(
                base,
                ours,
                theirs,
                &ScopeMarkers::bare(&MarkerFormat::default()),
            )
            .map(|r| (r.content, r.has_conflicts));
            assert_eq!(first, again, "statement merge is not a function");
        }
    }
}
