/// Three-way merge of a piece of text that is not a statement — the header, the
/// prelude, the tail, the footer.
fn merge_trivia(
    name: &str,
    b: &str,
    o: &str,
    t: &str,
    fmt: &ScopeMarkers<'_>,
    has_conflict: &mut bool,
) -> String {
    if o == t {
        return o.to_string();
    }
    if b == o {
        return t.to_string();
    }
    if b == t {
        return o.to_string();
    }
    if let Some(merged) = diffy_merge(b, o, t) {
        return merged;
    }
    *has_conflict = true;
    scoped_conflict_marker(name, Some(b), Some(o), Some(t), false, false, fmt)
}

