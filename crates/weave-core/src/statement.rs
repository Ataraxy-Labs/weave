/// Does this line continue the statement above it rather than start a new one?
///
/// Depth already answers that for anything inside brackets. What it cannot see
/// is the *grammatical* continuation that closes one block and opens the next
/// at the same depth and the same column — `} else {`, `elif`, `except`,
/// `finally`, `case`. Splitting there would hand the fold two half-statements
/// whose bodies could then be merged in either order, which is exactly the
/// interleaving this module exists to refuse.
fn is_continuation(trimmed: &str, prev: &str) -> bool {
    // A blank line starts nothing, so it continues whatever came before it.
    // Written as the `else` of the lookup rather than as a separate guard above
    // it: the guard and the `.unwrap()` that followed said the same thing
    // twice, and only one of them was checked by the compiler.
    let Some(first) = trimmed.chars().next() else {
        return true;
    };
    if matches!(
        first,
        '}' | ')' | ']' | ',' | '.' | '?' | ':' | ';' | '+' | '*' | '/' | '|' | '&' | '=' | '<'
    ) {
        return true;
    }
    let word = |k: &str| {
        trimmed == k
            || trimmed.starts_with(&format!("{k}:"))
            || trimmed.starts_with(&format!("{k} "))
            || trimmed.starts_with(&format!("{k}("))
            || trimmed.starts_with(&format!("{k}{{"))
    };
    const ARMS: [&str; 7] = [
        "else", "elif", "except", "finally", "catch", "when", "rescue",
    ];
    if ARMS.iter().any(|k| word(k)) {
        return true;
    }
    // `case` and `default` are the arms of a switch, and inside a switch body
    // they are the statement STARTS, not continuations — a switch whose arms
    // nobody can see is one statement, and two sides editing different arms of
    // it is then one conflict instead of two clean edits. What genuinely
    // continues is a fall-through LABEL: `case A:` immediately under `case B:`
    // with no body between them is one arm written on two lines.
    if word("case") || word("default") {
        return prev.ends_with(':');
    }
    false
}

/// Inclusive line spans of the statements in `lines[body_start..body_end)`.
///
/// A statement begins at the first column the body uses, at bracket depth zero,
/// on a line that neither continues the statement above it nor is trivia
/// belonging to the statement below it.
fn statement_spans(
    lines: &[&str],
    body_start: usize,
    body_end: usize,
) -> Option<Vec<(usize, usize)>> {
    if body_start >= body_end {
        return None;
    }
    let depth = depths(&lines[body_start..body_end])?;
    let first = lines[body_start..body_end]
        .iter()
        .position(|l| !l.trim().is_empty())?;
    let body_indent = {
        let l = lines[body_start + first];
        l.len() - l.trim_start().len()
    };
    // The fragment's OWN nesting level, not zero. A body sliced out of a larger
    // construct starts wherever it starts, and its statements are the lines that
    // return to that level.
    let base_depth = depth[first];

    let mut starts: Vec<usize> = Vec::new();
    let mut prev_code = "";
    for (off, line) in lines[body_start..body_end].iter().enumerate() {
        let trimmed = line.trim();
        if trimmed.is_empty() || is_trivia_line(line) {
            continue;
        }
        let prev = std::mem::replace(&mut prev_code, trimmed);
        if depth[off] != base_depth {
            continue;
        }
        let indent = line.len() - line.trim_start().len();
        if indent > body_indent {
            continue;
        }
        if is_continuation(trimmed, prev) {
            continue;
        }
        starts.push(body_start + off);
    }
    if starts.is_empty() {
        return None;
    }

    let mut spans: Vec<(usize, usize)> = Vec::new();
    for (i, &s) in starts.iter().enumerate() {
        let mut end = starts.get(i + 1).map(|n| n - 1).unwrap_or(body_end - 1);
        // Trailing blank lines and the next statement's own comment belong to
        // that statement's lead, so a deletion takes its own separator with it
        // and a comment travels with the thing it documents.
        while end > s && (lines[end].trim().is_empty() || is_trivia_line(lines[end])) {
            end -= 1;
        }
        spans.push((s, end));
    }
    Some(spans)
}

/// Walk back over the decorators, annotations and doc comment that belong to a
/// statement, stopping at `floor`.
fn attach_leading_trivia(lines: &[&str], start: usize, floor: usize) -> usize {
    let mut own = start;
    while own > floor && is_trivia_line(lines[own - 1]) {
        own -= 1;
    }
    own
}

/// (first body line, first footer line) for a BLOCK — a line that opens a
/// scope, whose body is the more-indented run beneath it.
///
/// Deliberately narrow: the opener must be the fragment's first non-blank line,
/// what follows it must be indented further, and a brace block must close on the
/// fragment's last non-blank line at the opener's own column. Anything looser
/// starts treating `data = {` as a scope and its entries as statements of the
/// enclosing body, which is how a reconstruction learns to move text.
fn block_wrapper(lines: &[&str]) -> Option<(usize, usize)> {
    let h = lines.iter().position(|l| !l.trim().is_empty())?;
    let opener = lines[h].trim_end();
    let indent = |l: &str| l.len() - l.trim_start().len();
    let next = lines[h + 1..].iter().position(|l| !l.trim().is_empty())? + h + 1;
    if indent(lines[next]) <= indent(lines[h]) {
        return None;
    }
    if opener.ends_with(':') {
        return Some((h + 1, lines.len()));
    }
    if opener.ends_with('{') {
        let last = lines.iter().rposition(|l| !l.trim().is_empty())?;
        if last > next
            && crate::merge::is_container_close_line(lines[last].trim())
            && indent(lines[last]) <= indent(lines[h])
        {
            return Some((h + 1, last));
        }
    }
    None
}

/// Tile a body into header / prelude / statements / tail / footer.
fn partition(content: &str) -> Option<Partition> {
    let lines: Vec<&str> = content.lines().collect();
    if lines.len() < 2 {
        return None;
    }
    // A body may or may not be wrapped. A function region is `fn f() { … }`; a
    // class attribute block or an interstitial run of statements is not wrapped
    // at all, and reading it as unwrapped is the honest reading rather than a
    // degradation.
    let (header_end, body_end) = match crate::merge::extract_container_wrapper(content) {
        Some((header, footer)) => {
            // Both pieces are slices OF `content` — a prefix and a suffix — so
            // the body's bounds are read off them directly rather than
            // recovered by a subtraction that would then need repairing. The
            // two sides cannot disagree about a length they do not both compute.
            let he = header.lines().count();
            let be = content[..content.len() - footer.len()].lines().count();
            if he > be {
                return None;
            }
            (he, be)
        }
        // `extract_container_wrapper` knows about declarations — `class`, `def`,
        // a brace on the signature line. A BLOCK is not a declaration, and the
        // recursive arm hands itself blocks: `if cond:` … , `for x in y {` … `}`.
        // Without this the fold recurses into a Python `if` and finds one
        // statement (the `if` itself), which is the shape it started from, so it
        // never looks inside a conditional in an indentation-scoped language at
        // all.
        None => block_wrapper(&lines).unwrap_or((0, lines.len())),
    };

    let spans = statement_spans(&lines, header_end, body_end)?;

    let mut parts: Vec<Part> = Vec::new();
    let mut cursor = header_end;
    for (i, &(start, end)) in spans.iter().enumerate() {
        let floor = if i == 0 { header_end } else { cursor };
        let own_start = attach_leading_trivia(&lines, start, floor);
        let lead = join(&lines[cursor..own_start]);
        let text = join(&lines[own_start..=end]);
        parts.push(Part {
            key: statement_key(&text),
            lead,
            text,
        });
        cursor = end + 1;
    }

    let prelude = parts
        .first_mut()
        .map(|p| std::mem::take(&mut p.lead))
        .unwrap_or_default();

    Some(Partition {
        header: join(&lines[..header_end]),
        prelude,
        parts,
        tail: join(&lines[cursor..body_end]),
        footer: join(&lines[body_end..]),
    })
}

