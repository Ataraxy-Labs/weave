/// What one side did to one base statement. The entity actions,
/// restricted to the actions a statement can carry: statements have no name
/// distinct from their content, so RENAMED and RENAME+EDITED collapse into
/// EDITED.
#[derive(Debug, Clone, PartialEq)]
enum Action {
    Unchanged,
    /// The side's index for the statement this base statement became.
    Edited(usize),
    Deleted,
}

/// The same action, holding the statement it acted on rather than an index
/// into a table the reader has to trust.
///
/// `Action::Edited(s)` says a side's statement `s` exists; resolving `s`
/// against that side's parts is a separate step, and for as long as the two
/// travelled separately — an `Action` beside an `Option<&Part>` — every cell of
/// the merge table that needed the statement reached for it with `.unwrap()`.
/// Six of them did. The implication was true, and enforced by nothing but the
/// match arm above each call: exactly the shape of gap that turns into a
/// runtime panic the day one arm's assumption stops holding, because nothing
/// in the type checks it.
///
/// Here the statement rides inside the variant, so `Edited` without a statement
/// does not exist to be unwrapped, and the match arms read it by binding it.
#[derive(Debug)]
enum SideEdit<'a> {
    Unchanged,
    Edited(&'a Part),
    Deleted,
}

impl<'a> SideEdit<'a> {
    /// Resolve one side's action against that side's parts, once, at the only
    /// place the action index and that side's table are both in scope.
    ///
    /// `locate` spends the side's claim — one claim type per version, so this
    /// stays a closure rather than a shared trait and a base claim still cannot
    /// be handed to the ours slot.
    fn resolve(action: &Action, parts: &'a [Part], locate: impl Fn(usize) -> usize) -> Self {
        match action {
            Action::Unchanged => SideEdit::Unchanged,
            // `align` writes `Edited(s)` only for an `s` it read out of this
            // side's own claim vector, and both vectors are minted once from
            // this side's partition — so the index is in range by construction.
            Action::Edited(s) => SideEdit::Edited(&parts[locate(*s)]),
            Action::Deleted => SideEdit::Deleted,
        }
    }

    /// The statement this side still has, for the trivia rules that ask about
    /// a side without caring whether it edited.
    fn part(&self) -> Option<&'a Part> {
        match self {
            SideEdit::Edited(p) => Some(p),
            _ => None,
        }
    }
}

/// One side's reading of the base sequence.
#[derive(Debug)]
struct Alignment {
    /// One action per base statement.
    per_base: Vec<Action>,
    /// `(gap, side index)` for each statement this side added, where `gap` is
    /// the base index the addition sits BEFORE (`base.len()` = at the end).
    additions: Vec<(usize, usize)>,
}

/// Longest common subsequence of two key sequences, as index pairs.
///
/// Bounded: a body with more statements than `MAX_LCS` cells is not merged at
/// statement level at all, because a quadratic table on an unbounded input is a
/// latency regression waiting for the one file that has it.
const MAX_LCS: usize = 250_000;

fn lcs_pairs(a: &[String], b: &[String]) -> Option<Vec<(usize, usize)>> {
    if a.len().saturating_mul(b.len()) > MAX_LCS {
        return None;
    }
    let (n, m) = (a.len(), b.len());
    let mut table = vec![0u32; (n + 1) * (m + 1)];
    let at = |i: usize, j: usize| i * (m + 1) + j;
    for i in (0..n).rev() {
        for j in (0..m).rev() {
            table[at(i, j)] = if a[i] == b[j] {
                table[at(i + 1, j + 1)] + 1
            } else {
                table[at(i + 1, j)].max(table[at(i, j + 1)])
            };
        }
    }
    let mut pairs = Vec::new();
    let (mut i, mut j) = (0usize, 0usize);
    while i < n && j < m {
        if a[i] == b[j] {
            pairs.push((i, j));
            i += 1;
            j += 1;
        } else if table[at(i + 1, j)] >= table[at(i, j + 1)] {
            i += 1;
        } else {
            j += 1;
        }
    }
    Some(pairs)
}

/// The similarity two unmatched statements in one gap need before they are read
/// as one statement EDITED rather than as a DELETE beside an ADD.
///
/// A wrong pairing here is not a loss — both readings keep every byte — but it
/// decides whether the other side's edit to the same statement is a merge or a
/// conflict, so the gate is set where an edit still looks like its origin.
const EDIT_SIMILARITY: f64 = 0.4;

/// The order-preserving matching of two unmatched runs that maximises total
/// similarity, keeping only pairs above [`EDIT_SIMILARITY`].
///
/// Ties are broken toward matching (and then toward advancing `a`), so the
/// result is a function of the two runs and nothing else — the comparison is on
/// integers scaled from the score rather than on floats, because a fold whose
/// shape depends on float association order is not a function either.
fn best_matching(a: &[String], b: &[String]) -> Vec<(usize, usize)> {
    /// Tighter than `MAX_LCS`, because each cell here costs a similarity
    /// computation over two whole statements rather than a string compare.
    const MAX_CELLS: usize = 20_000;
    let (n, m) = (a.len(), b.len());
    if n == 0 || m == 0 || n.saturating_mul(m) > MAX_CELLS {
        return Vec::new();
    }
    let score = |i: usize, j: usize| -> Option<i64> {
        let s = similarity(&a[i], &b[j]);
        if s >= EDIT_SIMILARITY {
            Some((s * 1_000_000.0) as i64)
        } else {
            None
        }
    };
    let mut dp = vec![0i64; (n + 1) * (m + 1)];
    let at = |i: usize, j: usize| i * (m + 1) + j;
    for i in (0..n).rev() {
        for j in (0..m).rev() {
            let skip = dp[at(i + 1, j)].max(dp[at(i, j + 1)]);
            let take = score(i, j).map(|s| s + dp[at(i + 1, j + 1)]).unwrap_or(0);
            dp[at(i, j)] = skip.max(take);
        }
    }
    let mut out = Vec::new();
    let (mut i, mut j) = (0usize, 0usize);
    while i < n && j < m {
        if let Some(s) = score(i, j) {
            if s + dp[at(i + 1, j + 1)] >= dp[at(i + 1, j)].max(dp[at(i, j + 1)]) {
                out.push((i, j));
                i += 1;
                j += 1;
                continue;
            }
        }
        if dp[at(i + 1, j)] >= dp[at(i, j + 1)] {
            i += 1;
        } else {
            j += 1;
        }
    }
    out
}

fn align(base: &Partition, side: &Partition) -> Option<Alignment> {
    let bk: Vec<String> = base.parts.iter().map(|p| p.key.clone()).collect();
    let sk: Vec<String> = side.parts.iter().map(|p| p.key.clone()).collect();
    let pairs = lcs_pairs(&bk, &sk)?;

    let mut per_base = vec![Action::Deleted; base.parts.len()];
    let mut additions: Vec<(usize, usize)> = Vec::new();

    // Walk the gaps between consecutive anchors, plus the head and tail gaps.
    let mut bi = 0usize;
    let mut si = 0usize;
    let mut anchors = pairs.to_vec();
    anchors.push((base.parts.len(), side.parts.len())); // sentinel tail gap
    for (ab, as_) in anchors {
        // Inside a gap nothing matched exactly, so the question is which of the
        // side's statements is the EDITED form of which of base's. Pairing them
        // by position is what a line differ does and it is wrong here for the
        // same reason it is wrong there: a statement inserted at the top of the
        // gap shunts every later pairing by one, and each shunted pair then
        // looks like a delete beside an add. The order-preserving matching that
        // maximises similarity is the reading that does not depend on where the
        // insertion happened to land.
        let matched = best_matching(&bk[bi..ab], &sk[si..as_]);
        let mut taken: Vec<bool> = vec![false; as_ - si];
        for &(bo, so) in &matched {
            per_base[bi + bo] = Action::Edited(si + so);
            taken[so] = true;
        }
        for (so, t) in taken.iter().enumerate() {
            if !t {
                additions.push((bi, si + so));
            }
        }
        // Surplus base statements in this gap stay `Deleted`.
        if ab < base.parts.len() {
            // The keys agree; the BYTES may not, because a key drops leading
            // indentation so that a statement which only moved still matches
            // itself. A re-indentation is an edit — emitting base's columns for
            // it would re-indent text nobody asked to re-indent, which is a
            // loss and not a formatting nicety.
            per_base[ab] = if base.parts[ab].text == side.parts[as_].text {
                Action::Unchanged
            } else {
                Action::Edited(as_)
            };
        }
        bi = ab + 1;
        si = as_ + 1;
    }
    Some(Alignment {
        per_base,
        additions,
    })
}

