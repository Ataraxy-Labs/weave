/// A move-once handle naming one statement of one version. Neither `Copy` nor
/// `Clone`, minted only by [`partition`], spent exactly once by the fold.
///
/// One type per version, so a base statement cannot be dropped into the ours
/// slot — the same trick `v2::types` plays for entities, for the same reason.
macro_rules! part_claim {
    ($name:ident) => {
        #[derive(Debug, PartialEq, Eq)]
        pub(crate) struct $name(usize);
        impl $name {
            fn new(i: usize) -> Self {
                Self(i)
            }
            fn index(&self) -> usize {
                self.0
            }
        }
    };
}

part_claim!(BasePart);
part_claim!(OursPart);
part_claim!(TheirsPart);

