// ---------------------------------------------------------------------------

/// Bracket depth *before* each line of `lines`, or `None` if the scan cannot be
/// trusted.
///
/// Indentation alone says a statement starts wherever a line returns to the
/// body's own column — which is false for any statement whose continuation
/// lines were not indented, and those are everywhere in real code:
///
/// ```text
/// foo(a,
/// b);
/// ```
///
/// So indentation proposes and depth vetoes: a line begins a statement only if
/// every bracket opened before it has been closed. When the scan ends
/// unbalanced the text is not something this reader understands — a language
/// with delimiters we do not model, an unclosed literal — and the honest answer
/// is `None`, which costs a conflict and never a wrong partition.
///
/// Quotes are resolved WITHIN a line: an opener with no closer on the same line
/// is not a string. That one rule is what lets the same scanner read Rust
/// lifetimes (`&'a str` — an apostrophe that opens nothing) and Python string
/// literals (`'x'` — one that does), without being told which language it is
/// looking at. Multi-line literals are exactly the two constructs that really do
/// span lines: block comments and triple quotes.
fn depths(lines: &[&str]) -> Option<Vec<i32>> {
    let mut out = Vec::with_capacity(lines.len());
    let mut depth: i32 = 0;
    let mut in_block_comment = false;
    let mut in_triple: Option<&'static str> = None;

    for line in lines {
        out.push(depth);
        let chars: Vec<char> = line.chars().collect();
        let offsets: Vec<usize> = line.char_indices().map(|(b, _)| b).collect();
        let rest_from = |i: usize| -> &str { &line[offsets[i]..] };
        let mut i = 0usize;
        while i < chars.len() {
            let c = chars[i];
            if let Some(q) = in_triple {
                if rest_from(i).starts_with(q) {
                    in_triple = None;
                    i += 3;
                } else {
                    i += 1;
                }
                continue;
            }
            if in_block_comment {
                if c == '*' && chars.get(i + 1) == Some(&'/') {
                    in_block_comment = false;
                    i += 2;
                } else {
                    i += 1;
                }
                continue;
            }
            let rest = rest_from(i);
            if rest.starts_with("\"\"\"") {
                in_triple = Some("\"\"\"");
                i += 3;
                continue;
            }
            if rest.starts_with("'''") {
                in_triple = Some("'''");
                i += 3;
                continue;
            }
            if rest.starts_with("/*") {
                in_block_comment = true;
                i += 2;
                continue;
            }
            if rest.starts_with("//") || c == '#' {
                break; // line comment (or a `#[attr]`, whose brackets balance)
            }
            if c == '"' || c == '\'' || c == '`' {
                match close_on_line(&chars, i, c) {
                    Some(end) => {
                        i = end + 1;
                        continue;
                    }
                    // No closer on this line: not a literal opener at all
                    // (a Rust lifetime, an English apostrophe in a comment we
                    // did not recognise). Read it as an ordinary character.
                    None => {
                        i += 1;
                        continue;
                    }
                }
            }
            match c {
                '(' | '[' | '{' => depth += 1,
                ')' | ']' | '}' => depth -= 1,
                _ => {}
            }
            i += 1;
        }
    }
    // An unterminated literal is the one state this reader cannot recover from:
    // everything after it was read as code that is not code, and no baseline
    // shift repairs that. An unbalanced *bracket* count is a different thing —
    // it means the text handed in is a fragment of something larger, which is
    // exactly what a recursive fold hands itself, and `statement_spans` reads
    // depth relative to the fragment's own level rather than to zero.
    if in_block_comment || in_triple.is_some() {
        return None;
    }
    Some(out)
}

/// Index of the closing quote matching the opener at `start`, on this line.
fn close_on_line(chars: &[char], start: usize, quote: char) -> Option<usize> {
    let mut i = start + 1;
    while i < chars.len() {
        if chars[i] == '\\' {
            i += 2;
            continue;
        }
        if chars[i] == quote {
            return Some(i);
        }
        i += 1;
    }
    None
}

