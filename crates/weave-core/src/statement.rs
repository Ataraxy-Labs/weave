/// One statement, with the unclaimed text that leads it.
#[derive(Debug, Clone)]
struct Part {
    /// The statement's structural key: its own text with per-line trailing
    /// whitespace and leading indentation removed, so a statement that only
    /// moved (and was re-indented by the move) still matches itself.
    key: String,
    /// Blank lines and section comments between the previous statement and this
    /// one's first own line. Travels with the statement it leads.
    lead: String,
    text: String,
}

/// One version of a body, tiled.
///
/// `header + prelude + Σ(lead + text) + tail + footer` reproduces the input
/// exactly. That equation is the property the whole module rests on and it is
/// asserted directly by `a_partition_tiles_the_body_it_came_from`.
#[derive(Debug)]
struct Partition {
    header: String,
    /// Text between the declaration and the first statement. A segment of the
    /// BODY, not of the statement that happens to follow it — the same reason
    /// `container::Decomposed::prelude` exists.
    prelude: String,
    parts: Vec<Part>,
    tail: String,
    footer: String,
}

impl Partition {
    /// Mint one claim per statement. The only constructor there is, so the
    /// claim multiset is exactly the statement multiset.
    fn claims<T>(&self, mk: impl Fn(usize) -> T) -> Vec<T> {
        (0..self.parts.len()).map(mk).collect()
    }
}

/// Join line slices back into text, one newline per line.
fn join(lines: &[&str]) -> String {
    let mut s = String::new();
    for l in lines {
        s.push_str(l);
        s.push('\n');
    }
    s
}

/// The structural key of a statement: content, normalized for the things that
/// are not content.
///
/// Trailing whitespace is not content. Leading indentation is not content
/// *of the statement* — a statement that moved from one block to another is the
/// same statement, re-indented — but it IS content of the file, which is why
/// the key is used only for MATCHING and never for emitting: what gets written
/// out is always some side's own bytes.
fn statement_key(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for line in text.lines() {
        let t = line.trim();
        if t.is_empty() {
            continue;
        }
        out.push_str(t);
        out.push('\n');
    }
    out
}

/// How much two unmatched statements in one gap look like each other — the only
/// question that decides whether they are one statement EDITED or a DELETE
/// standing beside an ADD.
///
/// Two readings, and the generous one wins. Word Jaccard is the right measure
/// for a statement with words in it; it is *useless* on the short ones that
/// dominate real bodies — `b();` and `b(2);` share no whitespace-delimited
/// token at all, so a word-only measure calls an edit of a one-call statement a
/// deletion, and then the other side's edit to it is a conflict rather than a
/// merge. Character bigrams see what words cannot at that length.
fn similarity(a: &str, b: &str) -> f64 {
    words_jaccard(a, b).max(bigram_jaccard(a, b))
}

fn jaccard<T: std::hash::Hash + Eq>(a: impl Iterator<Item = T>, b: impl Iterator<Item = T>) -> f64 {
    use std::collections::HashSet;
    let ta: HashSet<T> = a.collect();
    let tb: HashSet<T> = b.collect();
    if ta.is_empty() && tb.is_empty() {
        return 1.0;
    }
    let inter = ta.intersection(&tb).count() as f64;
    let union = ta.union(&tb).count() as f64;
    if union == 0.0 {
        0.0
    } else {
        inter / union
    }
}

fn words_jaccard(a: &str, b: &str) -> f64 {
    jaccard(word_tokens(a).into_iter(), word_tokens(b).into_iter())
}

fn bigram_jaccard(a: &str, b: &str) -> f64 {
    fn grams(s: &str) -> Vec<(char, char)> {
        let cs: Vec<char> = s.chars().filter(|c| !c.is_whitespace()).collect();
        cs.windows(2).map(|w| (w[0], w[1])).collect()
    }
    jaccard(grams(a).into_iter(), grams(b).into_iter())
}

